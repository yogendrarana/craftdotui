export type TokenCategory =
	| "core"
	| "semantic"
	| "form"
	| "sidebar"
	| "charts"
	| "typography"
	| "dimensions"
	| "shadows";

export type TokenType = "color" | "font" | "dimension" | "shadow";

export interface TokenDefinition {
	key: string; // e.g., "--background"
	label: string;
	category: TokenCategory;
	type: TokenType;
	description?: string;
	pairWith?: string; // e.g., "--foreground" for contrast checking
	isExtension?: boolean; // true if Craft UI semantic extension beyond standard shadcn
}

export type ThemeTokens = Record<string, string>;

export interface ThemePreset {
	id: string;
	name: string;
	description: string;
	badge?: string;
	light: ThemeTokens;
	dark: ThemeTokens;
}

